export function normalizeThemePresetName(raw: unknown): UiThemePresetName {
    if (typeof raw === 'string' && raw in presets) {
        return raw as UiThemePresetName;
    }
    return 'default';
}

export function normalizeThemeMode(raw: unknown): UiThemeMode {
    if (raw === 'auto' || raw === 'light' || raw === 'dark') {
        return raw;
    }
    if (raw === 'manual') return 'light';
    if (raw === 'system') return 'auto';
    return 'auto';
}

/**
 * Resolves persisted preset and mode values into their canonical independent pair.
 * Legacy merged preset values ('system' | 'light' | 'dark') take precedence over stale mode values
 * because the single-selector release wrote only `ui_theme_preset`.
 */
export function resolveStoredThemeSelection(
    rawPreset: unknown,
    rawMode: unknown
): { preset: UiThemePresetName; mode: UiThemeMode } {
    if (rawPreset === 'light') {
        return { preset: 'default', mode: 'light' };
    }
    if (rawPreset === 'dark') {
        return { preset: 'default', mode: 'dark' };
    }
    if (rawPreset === 'system') {
        return { preset: 'default', mode: 'auto' };
    }
    return {
        preset: normalizeThemePresetName(rawPreset),
        mode: normalizeThemeMode(rawMode)
    };
}

/**
 * Prior releases only shipped light palettes for `modern`, `recall`, and `archive`.
 * When upgrading into an effective dark scheme without a stored `ui_theme_mode`, any existing
 * `ui_theme` overrides were authored against the old light palette and must be discarded once.
 */
export function shouldClearLegacyThemeOverrides(
    rawPreset: unknown,
    hasStoredMode: boolean,
    effectiveScheme: UiThemeColorScheme
): boolean {
    if (hasStoredMode || effectiveScheme !== 'dark') {
        return false;
    }
    return rawPreset === 'modern' || rawPreset === 'recall' || rawPreset === 'archive';
}

export function resolveEffectiveColorScheme(
    mode: UiThemeMode,
    prefersDark: boolean
): UiThemeColorScheme {
    if (mode === 'auto') {
        return prefersDark ? 'dark' : 'light';
    }
    return mode;
}

export function resolvePresetThemeVars(
    preset: UiThemePresetName,
    mode: UiThemeMode,
    prefersDark: boolean
): UiThemeVars {
    const scheme = resolveEffectiveColorScheme(mode, prefersDark);
    return { ...presets[preset][scheme] };
}
